public class No {

    Integer conteudo;
    No noL;
    No noR;

    public No(Integer conteudo) {
        this.conteudo = conteudo;
    }

    public Integer getConteudo() {
        return conteudo;
    }

    public void setConteudo(Integer conteudo) {
        this.conteudo = conteudo;
    }

    public No getNoL() {
        return noL;
    }

    public void setNoL(No noL) {
        this.noL = noL;
    }

    public No getNoR() {
        return noR;
    }

    public void setNoR(No noR) {
        this.noR = noR;
    }
}
